#!/usr/bin/env python3
"""Read-only pyATS smoke checks for a real, reachable IOS/IOS-XE lab.

This testscript does not configure devices. It checks SSH/CLI access, required uplink
state and presence of the expected VLANs. It is intentionally not part of normal PR CI.
"""
from __future__ import annotations

import argparse
import re
import sys
from typing import Any

from pyats import aetest
from pyats.topology import loader

ROUTERS = ("HQ-R1", "BR1-R1", "BR2-R1")
SWITCHES = ("HQ-SW1", "BR1-SW1", "BR2-SW1")
REQUIRED_VLANS = {10: "STAFF", 20: "SERVERS", 30: "GUESTS", 99: "MGMT", 999: "BLACKHOLE"}
REQUIRED_UPLINKS = {
    "HQ-R1": ("GigabitEthernet0/0", "GigabitEthernet0/1"),
    "BR1-R1": ("GigabitEthernet0/0", "GigabitEthernet0/1"),
    "BR2-R1": ("GigabitEthernet0/0", "GigabitEthernet0/1"),
    "HQ-SW1": ("GigabitEthernet0/1",),
    "BR1-SW1": ("GigabitEthernet0/1",),
    "BR2-SW1": ("GigabitEthernet0/1",),
}


def connect(device: Any) -> None:
    """Open a CLI connection using testbed credentials, suppressing terminal mirroring."""
    device.connect(log_stdout=False)


def disconnect(device: Any) -> None:
    """Attempt a tidy disconnect without hiding an earlier test failure."""
    try:
        device.disconnect()
    except Exception:
        pass


class NetworkSmoke(aetest.Testcase):
    @aetest.test
    def every_device_responds_to_read_only_cli(self, testbed) -> None:
        failures = []
        for name, device in testbed.devices.items():
            try:
                connect(device)
                output = device.execute("show version")
                if not output or not output.strip():
                    failures.append(f"{name}: 'show version' returned no output")
            except Exception as exc:
                failures.append(f"{name}: connection/command failed ({type(exc).__name__}: {exc})")
            finally:
                disconnect(device)
        if failures:
            self.failed("Read-only CLI smoke test failed:\n" + "\n".join(failures))

    @aetest.test
    def expected_vlans_exist_on_all_access_switches(self, testbed) -> None:
        failures = []
        for name in SWITCHES:
            device = testbed.devices[name]
            try:
                connect(device)
                output = device.execute("show vlan brief")
                for vlan_id, vlan_name in REQUIRED_VLANS.items():
                    pattern = rf"(?m)^\s*{vlan_id}\s+{re.escape(vlan_name)}\s+"
                    if not re.search(pattern, output, flags=re.IGNORECASE):
                        failures.append(f"{name}: VLAN {vlan_id} ({vlan_name}) not found in 'show vlan brief'")
            except Exception as exc:
                failures.append(f"{name}: VLAN check failed ({type(exc).__name__}: {exc})")
            finally:
                disconnect(device)
        if failures:
            self.failed("VLAN smoke test failed:\n" + "\n".join(failures))

    @aetest.test
    def expected_uplinks_are_up_up(self, testbed) -> None:
        failures = []
        for name, interfaces in REQUIRED_UPLINKS.items():
            device = testbed.devices[name]
            for interface in interfaces:
                try:
                    connect(device)
                    output = device.execute(f"show interfaces {interface}")
                    normalized = " ".join(output.lower().split())
                    if "is up, line protocol is up" not in normalized:
                        failures.append(f"{name}/{interface}: interface is not operationally up/up")
                except Exception as exc:
                    failures.append(f"{name}/{interface}: interface check failed ({type(exc).__name__}: {exc})")
                finally:
                    disconnect(device)
        if failures:
            self.failed("Uplink smoke test failed:\n" + "\n".join(failures))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--testbed", required=True, help="YAML generated by scripts/build_pyats_testbed.py")
    args, _unknown = parser.parse_known_args()
    try:
        testbed = loader.load(args.testbed)
    except Exception as exc:
        print(f"Could not load pyATS testbed {args.testbed}: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc
    # Use pyATS' standard entry point so its test-result exit status is preserved.
    aetest.main(testbed=testbed)


if __name__ == "__main__":
    main()
